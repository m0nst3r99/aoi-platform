from dataclasses import FrozenInstanceError, replace
from math import cos, inf, nan, radians, sin
from random import Random

import pytest

from aoi_platform.geometry import (
    AxisDirection, ErrorCode, Frame, FrameKind, GeometryError, Matrix3, Parity,
    Point2, Transform2, TransformKind, Unit, signed_angular_difference,
)

MM_TOL = 1e-6  # synthetic-geometry-v1, not a production accuracy claim
IDENTITY: Matrix3 = ((1, 0, 0), (0, 1, 0), (0, 0, 1))


def xy(point: Point2) -> tuple[float, float]:
    return point.x, point.y


def test_required_chain_and_independent_inverse_checkpoints(
    mm_frame: Frame, inch_frame: Frame
) -> None:
    reflected = replace(mm_frame, frame_id="reflected", y_direction=AxisDirection.DOWN)
    rotated = replace(mm_frame, frame_id="rotated")
    pcb = replace(mm_frame, frame_id="pcb", kind=FrameKind.PCB, origin="PCB datum")
    scale = Transform2.unit_conversion(inch_frame, mm_frame, transform_id="units")
    mirror = Transform2.reflection(mm_frame, reflected, axis="y", transform_id="mirror")
    rotate = Transform2.rotation(reflected, rotated, 90, transform_id="rotate")
    translate = Transform2.translation(rotated, pcb, 10, 20, transform_id="translate")

    p0 = Point2(1, 2, inch_frame)
    p1 = scale.apply(p0)
    p2 = mirror.apply(p1)
    p3 = rotate.apply(p2)
    p4 = translate.apply(p3)
    for point, expected in zip(
        (p1, p2, p3, p4),
        ((25.4, 50.8), (25.4, -50.8), (50.8, 25.4), (60.8, 45.4)),
        strict=True,
    ):
        assert xy(point) == pytest.approx(expected, rel=0, abs=MM_TOL)

    chain = translate.compose(
        rotate.compose(mirror.compose(scale, transform_id="mirror-scale"), transform_id="rotate-mirror-scale"),
        transform_id="source-to-pcb",
    )
    assert chain.matrix[0] == pytest.approx((0, 25.4, 10), rel=0, abs=1e-12)
    assert chain.matrix[1] == pytest.approx((25.4, 0, 20), rel=0, abs=1e-12)
    assert xy(chain.apply(p0)) == pytest.approx((60.8, 45.4), rel=0, abs=MM_TOL)
    assert chain.from_frame == inch_frame and chain.to_frame == pcb
    assert chain.parity is Parity.REFLECTED
    assert "units" in chain.provenance and "translate" in chain.provenance

    current = Point2(60.8, 45.4, pcb)  # Independent literal, not generated by apply.
    for transform, expected in zip(
        (translate, rotate, mirror, scale),
        ((50.8, 25.4), (25.4, -50.8), (25.4, 50.8), (1, 2)),
        strict=True,
    ):
        current = transform.inverse(transform_id=f"inverse-{transform.transform_id}").apply(current)
        assert xy(current) == pytest.approx(expected, rel=0, abs=1e-9)
    recovered = chain.inverse(transform_id="inverse-chain").apply(p4)
    assert recovered.frame == inch_frame
    assert abs(recovered.x - 1) * 25.4 <= MM_TOL
    assert abs(recovered.y - 2) * 25.4 <= MM_TOL


def test_mm_to_inch_oracle_and_same_unit_identity(mm_frame: Frame, inch_frame: Frame) -> None:
    transform = Transform2.unit_conversion(mm_frame, inch_frame, transform_id="mm-to-inch")
    assert xy(transform.apply(Point2(25.4, -50.8, mm_frame))) == pytest.approx((1, -2), abs=1e-12)
    identity = Transform2.unit_conversion(mm_frame, mm_frame, transform_id="same-unit")
    assert identity.apply(Point2(2, -3, mm_frame)) == Point2(2, -3, mm_frame)


def test_bottom_reflection_preserves_angle_and_parity_semantics(mm_frame: Frame) -> None:
    top = replace(mm_frame, frame_id="top-view")
    mirror = Transform2.reflection(mm_frame, top, axis="x", offset=5, transform_id="bottom-to-top")
    assert xy(mirror.apply(Point2(2, 3, mm_frame))) == (8, 3)
    assert mirror.map_orientation(0) == (180, Parity.REFLECTED)
    angle, parity = mirror.map_orientation(30)
    assert angle == pytest.approx(150, abs=1e-12)  # Not simply -30.
    assert parity is Parity.REFLECTED
    inverse = mirror.inverse(transform_id="top-to-bottom")
    angle, parity = inverse.map_orientation(angle, parity)
    assert angle == pytest.approx(30, abs=1e-12)
    assert parity is Parity.PRESERVED
    doubled = inverse.compose(mirror, transform_id="two-mirrors")
    assert doubled.parity is Parity.PRESERVED
    assert doubled.apply(Point2(2, 3, mm_frame)) == Point2(2, 3, mm_frame)


def test_bottom_named_source_is_not_automatically_mirrored(mm_frame: Frame) -> None:
    bottom = replace(mm_frame, frame_id="bottom-layer-already-top-view")
    explicit = Transform2("identity", bottom, mm_frame, IDENTITY)
    assert xy(explicit.apply(Point2(2, 3, bottom))) == (2, 3)
    assert explicit.parity is Parity.PRESERVED


def test_noncommuting_transforms_apply_inner_first(mm_frame: Frame) -> None:
    rotate = Transform2.rotation(mm_frame, mm_frame, 90, transform_id="rotate")
    move = Transform2.translation(mm_frame, mm_frame, 10, 0, transform_id="move")
    p = Point2(1, 2, mm_frame)
    assert xy(move.compose(rotate, transform_id="rotate-then-move").apply(p)) == pytest.approx((8, 1))
    assert xy(rotate.compose(move, transform_id="move-then-rotate").apply(p)) == pytest.approx((-2, 11))


def test_affine_shear_oracle_inverse_and_orientation(mm_frame: Frame) -> None:
    shear = Transform2("shear", mm_frame, mm_frame, ((1, 2, 3), (0, 1, -4), (0, 0, 1)))
    assert xy(shear.apply(Point2(5, 6, mm_frame))) == (20, 2)
    assert xy(shear.inverse(transform_id="undo").apply(Point2(20, 2, mm_frame))) == (5, 6)
    assert shear.map_orientation(0) == (0, Parity.PRESERVED)
    assert shear.condition_number == pytest.approx(5.82842712474619)


@pytest.mark.parametrize("scale", [1e-150, 1e150])
def test_condition_check_is_scale_normalized(mm_frame: Frame, scale: float) -> None:
    transform = Transform2("scale", mm_frame, mm_frame, ((scale, 0, 0), (0, scale, 0), (0, 0, 1)))
    assert transform.condition_number == 1
    p = Point2(2, -3, mm_frame)
    assert xy(transform.inverse(transform_id="inverse").apply(transform.apply(p))) == pytest.approx((2, -3))


def test_condition_policy_boundary(mm_frame: Frame) -> None:
    boundary = Transform2("boundary", mm_frame, mm_frame, ((1, 0, 0), (0, 1e-8, 0), (0, 0, 1)))
    assert boundary.condition_number <= 1e8
    assert boundary.policy_id == "synthetic-geometry-v1"
    with pytest.raises(GeometryError) as caught:
        Transform2("over-boundary", mm_frame, mm_frame, ((1, 0, 0), (0, 0.999e-8, 0), (0, 0, 1)))
    assert caught.value.code is ErrorCode.TRANSFORM_ILL_CONDITIONED


def test_seeded_forward_oracles_and_round_trips(mm_frame: Frame, inch_frame: Frame) -> None:
    rng = Random(1007)
    samples = [(0, 0), (280, 550), (-280, -550), (0, 550), (280, 0)]
    samples += [(rng.uniform(-550, 550), rng.uniform(-550, 550)) for _ in range(200)]
    for index, (x, y) in enumerate(samples):
        source = inch_frame if index % 2 else mm_frame
        factor = 25.4 if source.unit is Unit.INCH else 1.0
        theta = rng.uniform(-720, 720)
        dx, dy = rng.uniform(-550, 550), rng.uniform(-550, 550)
        scale = Transform2.unit_conversion(source, mm_frame, transform_id="units")
        reflect = Transform2.reflection(mm_frame, mm_frame, axis="y", transform_id="reflect")
        rotate = Transform2.rotation(mm_frame, mm_frame, theta, transform_id="rotate")
        translate = Transform2.translation(mm_frame, mm_frame, dx, dy, transform_id="translate")
        chain = translate.compose(rotate, transform_id="pose").compose(
            reflect.compose(scale, transform_id="reflect-units"), transform_id="chain"
        )
        # Scalar oracle calculated from original coordinates; no transform helpers.
        expected_x = factor * (x*cos(radians(theta)) + y*sin(radians(theta))) + dx
        expected_y = factor * (x*sin(radians(theta)) - y*cos(radians(theta))) + dy
        result = chain.apply(Point2(x, y, source))
        assert xy(result) == pytest.approx((expected_x, expected_y), rel=0, abs=MM_TOL)
        recovered = chain.inverse(transform_id="inverse").apply(result)
        assert abs(recovered.x - x) * factor <= MM_TOL
        assert abs(recovered.y - y) * factor <= MM_TOL
        mapped_angle, parity = chain.map_orientation(37)
        assert abs(signed_angular_difference(mapped_angle, theta - 37)) <= 1e-10
        original_angle, original_parity = chain.inverse(transform_id="orientation-inverse").map_orientation(mapped_angle, parity)
        assert abs(signed_angular_difference(original_angle, 37)) <= 1e-10
        assert original_parity is Parity.PRESERVED


@pytest.mark.parametrize("matrix,code", [
    (((0, 0, 0), (0, 0, 0), (0, 0, 1)), ErrorCode.TRANSFORM_SINGULAR),
    (((1, 2, 0), (2, 4, 0), (0, 0, 1)), ErrorCode.TRANSFORM_SINGULAR),
    (((1, 0, 0), (0, 1e-9, 0), (0, 0, 1)), ErrorCode.TRANSFORM_ILL_CONDITIONED),
    (((1, 0, nan), (0, 1, 0), (0, 0, 1)), ErrorCode.SCHEMA_INVALID),
    (((inf, 0, 0), (0, 1, 0), (0, 0, 1)), ErrorCode.SCHEMA_INVALID),
    (((True, 0, 0), (0, 1, 0), (0, 0, 1)), ErrorCode.SCHEMA_INVALID),
    (((1, 0, 0), (0, 1, 0), (0.1, 0, 1)), ErrorCode.SCHEMA_INVALID),
    (((1, 0, 0), (0, 1, 0), (0, 0, 2)), ErrorCode.SCHEMA_INVALID),
    (((1, 0), (0, 1)), ErrorCode.SCHEMA_INVALID),
    ([[1, 0, 0], [0, 1, 0], [0, 0, 1]], ErrorCode.SCHEMA_INVALID),
])
def test_invalid_matrices_fail_explicitly(mm_frame: Frame, matrix: Matrix3, code: ErrorCode) -> None:
    with pytest.raises(GeometryError) as caught:
        Transform2("invalid", mm_frame, mm_frame, matrix)
    assert caught.value.code is code
    assert caught.value.field_path.startswith("transform.matrix")


@pytest.mark.parametrize("updates", [
    {"frame_id": "different"}, {"origin": "different origin"}, {"unit": Unit.INCH},
    {"board_revision_id": "rev-other"}, {"machine_id": "other-machine"},
    {"y_direction": AxisDirection.DOWN}, {"capture_id": "other-capture"},
])
def test_apply_and_composition_require_exact_intermediate_frame(mm_frame: Frame, updates: dict) -> None:
    other = replace(mm_frame, **updates)
    base = Transform2("base", mm_frame, mm_frame, IDENTITY)
    with pytest.raises(GeometryError) as caught:
        base.apply(Point2(0, 0, other))
    assert caught.value.code is ErrorCode.CONTEXT_MISMATCH
    other_transform = Transform2("other", other, other, IDENTITY)
    with pytest.raises(GeometryError) as caught:
        base.compose(other_transform, transform_id="bad")
    assert caught.value.code is ErrorCode.CONTEXT_MISMATCH


