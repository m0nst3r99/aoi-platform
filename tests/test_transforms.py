def test_transform_metadata_and_public_inputs_are_validated(mm_frame: Frame) -> None:
    base = Transform2("base", mm_frame, mm_frame, IDENTITY)
    for updates in (
        {"transform_id": " "}, {"kind": "homography"}, {"provenance": ()},
        {"provenance": ["mutable"]}, {"provenance": ("",)}, {"from_frame": "id-only"},
    ):
        with pytest.raises(GeometryError):
            replace(base, **updates)
    with pytest.raises(FrozenInstanceError):
        base.matrix = IDENTITY  # type: ignore[misc]
    with pytest.raises(GeometryError):
        base.apply((1, 2))  # type: ignore[arg-type]
    with pytest.raises(GeometryError):
        base.compose(None, transform_id="bad")  # type: ignore[arg-type]
    with pytest.raises(GeometryError):
        base.map_orientation(0, "reflected")  # type: ignore[arg-type]
    with pytest.raises(GeometryError):
        Transform2.reflection(mm_frame, mm_frame, axis="z", transform_id="bad")  # type: ignore[arg-type]


def test_numeric_overflow_is_a_typed_failure(mm_frame: Frame) -> None:
    huge = Transform2("huge", mm_frame, mm_frame, ((1e308, 0, 0), (0, 1e308, 0), (0, 0, 1)))
    with pytest.raises(GeometryError):
        huge.apply(Point2(10, 10, mm_frame))
    with pytest.raises(GeometryError):
        huge.compose(huge, transform_id="overflow")
    tiny = Transform2("tiny", mm_frame, mm_frame, ((1e-310, 0, 0), (0, 1e-310, 0), (0, 0, 1)))
    with pytest.raises(GeometryError):
        tiny.inverse(transform_id="unrepresentable-inverse")
