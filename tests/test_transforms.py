def test_units_and_datums_cannot_be_assumed(mm_frame: Frame, inch_frame: Frame) -> None:
    for operation in (
        lambda: Transform2.rotation(inch_frame, mm_frame, 90, transform_id="bad"),
        lambda: Transform2.translation(inch_frame, mm_frame, 1, 2, transform_id="bad"),
        lambda: Transform2.unit_conversion(inch_frame, replace(mm_frame, origin="unknown other datum"), transform_id="bad"),
        lambda: Transform2.unit_conversion(inch_frame, replace(mm_frame, y_direction=AxisDirection.DOWN), transform_id="bad"),
    ):
        with pytest.raises(GeometryError):
            operation()
    px = replace(mm_frame, frame_id="pixel", unit=Unit.PIXEL)
    for source, target in ((px, mm_frame), (mm_frame, px), (px, px)):
        with pytest.raises(GeometryError):
            Transform2.unit_conversion(source, target, transform_id="not-calibration")
    with pytest.raises(GeometryError):
        Transform2("not-calibration", mm_frame, px, IDENTITY)


